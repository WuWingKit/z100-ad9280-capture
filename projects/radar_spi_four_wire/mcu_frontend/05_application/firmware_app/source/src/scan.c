uint8_t adt_scan_set_beam(uint8_t beamIndex)
{
    if(beamIndex >= APP_BEAM_COUNT)
    {
        return 0u;
    }
    return AppHardware_SetBeam(g_appBeamTx[beamIndex].psr,
                               g_appBeamRx[beamIndex].psr);
}

uint8_t adt_scan_prepare_beam(uint8_t beamIndex)
{
    if(beamIndex >= APP_BEAM_COUNT)
    {
        return 0u;
    }
    return AppHardware_PrepareBeam(g_appBeamTx[beamIndex].psr,
                                   g_appBeamRx[beamIndex].psr);
}

uint8_t adt_scan_load_beam(void)
{
    return AppHardware_LoadBeam();
}

uint8_t adt_scan_acquire_start(uint32_t adcDestinationAddr)
{
    return AppHardware_CaptureStart(adcDestinationAddr);
}

uint8_t adt_scan_acquire_wait(void)
{
    return AppHardware_CaptureWait();
}
